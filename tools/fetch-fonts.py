#!/usr/bin/env python3
"""Downloads the site's web fonts (Fraunces, Onest, DM Mono: the files Google Fonts serves for the approved pages)
into app/fonts/ and writes app/fonts/fonts.css with the same @font-face rules pointing at the local files.
The Next.js app serves them itself (same origin, fingerprinted, cached long-term): no request to Google at runtime.
Run again only to update the fonts: python3 tools/fetch-fonts.py
The fonts are licensed under the SIL Open Font License 1.1 (see app/fonts/LICENSE.md)."""
import pathlib, re, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'app/fonts'
CSS_URL = ('https://fonts.googleapis.com/css2?family=DM+Mono:wght@400;500'
           '&family=Fraunces:ital,opsz,wght@0,9..144,200..700;1,9..144,200..700&family=Onest:wght@300..700&display=swap')
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36'  # asks for woff2

def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': UA}), timeout=60).read()

css = get(CSS_URL).decode()
OUT.mkdir(parents=True, exist_ok=True)
blocks = re.findall(r'/\* ([\w-]+) \*/\s*(@font-face \{.*?\})', css, re.S)
out = ['/* Self-hosted web fonts (generated by tools/fetch-fonts.py from the stylesheet the approved pages load).',
       '   Same files and @font-face rules as Google Fonts serves, so text renders identically. SIL OFL 1.1. */']
for subset, block in blocks:
    family = re.search(r"font-family: '([^']+)'", block).group(1)
    style = re.search(r'font-style: (\w+)', block).group(1)
    weight = re.search(r'font-weight: ([\d ]+);', block).group(1).replace(' ', '-')
    url = re.search(r'url\((https://[^)]+)\)', block).group(1)
    name = f"{family.lower().replace(' ', '-')}-{style}-{weight}-{subset}.woff2"
    (OUT / name).write_bytes(get(url))
    out.append(f'/* {subset} */\n' + block.replace(url, f'./{name}'))
(OUT / 'fonts.css').write_text('\n'.join(out) + '\n', encoding='utf-8')
print(f'wrote {len(blocks)} font files and app/fonts/fonts.css')
